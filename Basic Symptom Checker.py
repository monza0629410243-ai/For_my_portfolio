URGENT_SYMPTOMS = {"10"}


def ask_confirmation():
    while True:
        answer = input("คุณต้องการใช้งานโปรแกรมทดสอบนี้หรือไม่? (y/n) >>> ").strip().lower()
        if answer in ("y", "yes", "ใช่"):
            return True
        elif answer in ("n", "no", "ไม่"):
            return False
        else:
            print("กรุณาพิมพ์ y (ใช่) หรือ n (ไม่) เท่านั้น")


def show_menu():
    print("\n" + "=" * 50)
    print("     โปรแกรมประเมินอาการเบื้องต้น (Basic)")
    print("=" * 50)
    print("*** ไม่ใช่การวินิจฉัยทางการแพทย์ ใช้เพื่อการศึกษาเท่านั้น ***")
    print("-" * 50)
    for key, label in SYMPTOMS.items():
        print(f"  {key:>2}. {label}")
    print("-" * 50)
    print("พิมพ์หมายเลขอาการ คั่นด้วยจุลภาค เช่น 1,3,5")
    print("พิมพ์ 'menu' เพื่อดูเมนูอีกครั้ง, 'exit' เพื่อออก")
    print("=" * 50)


def parse_selection(user_input):
    parts = [p.strip() for p in user_input.split(",") if p.strip()]
    valid = set()
    invalid = []
    for p in parts:
        if p in SYMPTOMS:
            valid.add(p)
        else:
            invalid.append(p)
    return valid, invalid


def analyze(selected_keys):
    matched_groups = []
    for group in GROUPS:
        overlap = selected_keys & group["keys"]
        if len(overlap) >= group["min_match"]:
            matched_groups.append(group)

    print("\n--- ผลการประเมินเบื้องต้น ---")

    if not matched_groups:
        print("ไม่พบรูปแบบอาการที่ตรงกับกลุ่มอาการทั่วไปในระบบนี้ชัดเจน")
    else:
        for group in matched_groups:
            print(f"\n• {group['name']}")
            print("  คำแนะนำการดูแลตัวเองเบื้องต้น:")
            for tip in group["advices"]:
                print(f"    - {tip}")

    if selected_keys & URGENT_SYMPTOMS:
        print("\n⚠️  อาการที่ระบุ (เช่น แน่นหน้าอก/หายใจลำบาก) ควรไปพบแพทย์ทันที")
        print("    หากอาการรุนแรงฉับพลัน ให้ไปห้องฉุกเฉินหรือโทรสายด่วนการแพทย์ฉุกเฉิน 1669")

    print(
        "\nหมายเหตุ: โปรแกรมนี้ให้ข้อมูลทั่วไปเท่านั้น ไม่สามารถวินิจฉัยโรค "
        "หรือแนะนำยาได้ หากอาการไม่ดีขึ้นภายใน 2-3 วัน มีไข้สูงต่อเนื่อง "
        "หรืออาการรุนแรง/เรื้อรัง ควรปรึกษาแพทย์หรือเภสัชกรโดยตรง"
    )


def main():
    if not ask_confirmation():
        print("\nขอบคุณที่แวะมาครับ ดูแลสุขภาพด้วยนะครับ")
        return

    show_menu()
    while True:
        user_input = input("\nเลือกอาการ >>> ").strip()

        if user_input.lower() == "exit":
            print("ขอบคุณที่ใช้งานครับ ดูแลสุขภาพด้วยนะครับ")
            break
        elif user_input.lower() == "menu":
            show_menu()
            continue
        elif not user_input:
            continue

        selected, invalid = parse_selection(user_input)

        if invalid:
            print(f"หมายเลขไม่ถูกต้อง: {', '.join(invalid)} (พิมพ์ 'menu' เพื่อดูรายการอาการ)")

        if selected:
            analyze(selected)


if __name__ == "__main__":
    main()