URGENT_SYMPTOMS = {"7"}
def ask_confirmation():
    while True:
        answer = input("ต้องการเปิดใช้งานโปรแกรมตรวจเช็กอาการรถยนต์ (ช่างรุ่นเก๋า / G-Scan) หรือไม่? (y/n) >>> ").strip().lower()
        if answer in ("y", "yes", "ใช่"):
            return True
        elif answer in ("n", "no", "ไม่"):
            return False
        else:
            print("กรุณาพิมพ์ y (ใช่) หรือ n (ไม่) เท่านั้นครับ")


def show_menu():
    print("\n" + "=" * 60)
    print("     โปรแกรมผู้ช่วยช่าง: ตรวจเช็กและซ่อมรถยนต์ (ปี 2000 ขึ้นไป)")
    print("=" * 60)
    print("*** เน้นใช้ร่วมกับเครื่องมือสแกน G-Scan และประสบการณ์หน้างานช่าง ***")
    print("-" * 60)
    for key, label in SYMPTOMS.items():
        print(f"  {key:>2}. {label}")
    print("-" * 60)
    print("พิมพ์เลือกหมายเลขอาการ คั่นด้วยเครื่องหมายจุลภาค เช่น 1,3,4")
    print("พิมพ์ 'menu' เพื่อดูรายการอาการอีกครั้ง, หรือพิมพ์ 'exit' เพื่อออก")
    print("=" * 60)


def parse_selection(user_input):
    parts = [p.strip() for p in user_input.split(",") if p.strip()]
    valid = set()
    invalid = []
    for p in parts:
        if p in SYMPTOMS:
            valid.add(p)
        else:
            invalid.append(p)
    return valid, invalid


def analyze(selected_keys):
    matched_groups = []
    for group in GROUPS:
        overlap = selected_keys & group["keys"]
        if len(overlap) >= group["min_match"]:
            matched_groups.append(group)

    print("\n--- ผลการวิเคราะห์และแนวทางการซ่อมสำหรับช่าง ---")

    if not matched_groups:
        print("ไม่พบกลุ่มอาการที่ตรงกับรายการหลัก ลองเลือกใหม่อีกครั้งครับ")
    else:
        for group in matched_groups:
            print(n_str := f"\n• {group['name']}")
            print("  วิธีตรวจสอบและแก้ไขหน้างาน:")
            for tip in group["advices"]:
                print(f"    - {tip}")

    if selected_keys & URGENT_SYMPTOMS:
        print("\n⚠️  เตือนภัยด่วน: อาการเครื่องยนต์ความร้อนขึ้นสูง (Overheat) อันตรายมาก!")
        print("    ต้องรีบสั่งลูกค้าหรือจอดรถทันที ห้ามฝืนขับเด็ดขาด ไม่งั้นฝาสูบพังแน่ๆ")

    print(
        "\nคำแนะนำเพิ่มเติม: ระบบนี้เป็นแนวทางเบื้องต้นสำหรับรถยุค OBD-II (ปี 2000+) "
        "หน้างานจริงควรใช้เครื่อง G-Scan อ่านค่าสด (Data List) ควบคู่กับการใช้ประสบการณ์ช่างร่วมด้วยเสมอ"
    )


def main():
    if not ask_confirmation():
        print("\nไว้โอกาสหน้าค่อยมาใช้งานใหม่ครับ ขอให้งานซ่อมราบรื่นครับ!")
        return

    show_menu()
    while True:
        user_input = input("\nเลือกอาการเสียของรถ >>> ").strip()

        if user_input.lower() == "exit":
            print("ปิดโปรแกรมเรียบร้อย ขอให้โชคดีกับการซ่อมรถครับ!")
            break
        elif user_input.lower() == "menu":
            show_menu()
            continue
        elif not user_input:
            continue

        selected, invalid = parse_selection(user_input)

        if invalid:
            print(f"หมายเลขไม่ถูกต้อง: {', '.join(invalid)} (พิมพ์ 'menu' เพื่อดูรายการอาการอีกครั้ง)")

        if selected:
            analyze(selected)


if __name__ == "__main__":
    main()